import type { BuildStep } from '@/features/maoLab/domain/types'

function step(
  partial: Omit<BuildStep, 'connections' | 'wiring' | 'troubleshooting' | 'safety'> &
    Partial<Pick<BuildStep, 'connections' | 'wiring' | 'troubleshooting' | 'safety' | 'blockedReason' | 'unlocks3d'>>,
): BuildStep {
  return {
    connections: partial.connections ?? [],
    wiring: partial.wiring ?? ['See PINOUT / how-to-connect guides'],
    troubleshooting: partial.troubleshooting ?? ['Confirm power rails and GND first'],
    safety: partial.safety ?? ['Disconnect USB before rewiring'],
    ...partial,
  }
}

