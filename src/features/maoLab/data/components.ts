/** Core demo parts + full RFID-kit inventory (catalog). */
export const MAO_PARTS: readonly MaoHardwarePart[] = [...MAO_CORE_PARTS, ...MAO_KIT_INVENTORY]

export function listMaoParts(): readonly MaoHardwarePart[] {
  return MAO_PARTS
}

export function findMaoPart(id: string): MaoHardwarePart | undefined {
  return MAO_PARTS.find((part) => part.id === id)
}

export function listMaoCategories(): readonly MaoHardwarePart['category'][] {
  return [...new Set(MAO_PARTS.map((part) => part.category))]
}
